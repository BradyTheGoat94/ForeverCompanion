function ForeverCompanionSpecPlaybookLines(classToken)
 local planner=ForeverCompanionSpecPlanner
 if type(planner)~="table" or type(planner.Get)~="function" then return {} end
 local selected=planner.Get(classToken)
 local name=type(selected)=="table" and selected[1]
 local class=ForeverCompanionSpecPlaybooks[classToken]
 local steps=type(class)=="table" and class[name]
 if type(steps)~="table" then return {} end
 local lines={"BEGINNER BUTTON ORDER | "..name.." | ADVISORY"}
 for i,step in ipairs(steps) do lines[#lines+1]=i..". "..step end
 lines[#lines+1]="These are practice decisions, not an automated rotation. Skip untrained spells."
 lines[#lines+1]="Sources: Blizzard class deep dives; mobalytics.gg/wow-forever/classes; Wowhead Forever tuning."
 return lines
end
